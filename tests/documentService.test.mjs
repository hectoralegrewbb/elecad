import assert from 'node:assert/strict';
import { createDefaultCatalog } from '../src/data/defaultCatalog.js';
import { createCommands } from '../src/core/commands.js';
import { DocumentStore } from '../src/core/documentStore.js';
import { createEmptyState } from '../src/core/documentState.js';
import { DocumentService } from '../src/app/documentService.js';
import { RouteService } from '../src/core/routeService.js';
import { WireRouter } from '../src/core/wireRouter.js';
import { SelectionModel } from '../src/interaction/selectionModel.js';
import { Viewport } from '../src/render/viewport.js';
const catalog = createDefaultCatalog();
const store = new DocumentStore(createEmptyState());
const commands = createCommands(catalog);
const routeService = new RouteService(catalog,new WireRouter());
const editor = {store,commands,catalog,selection:new SelectionModel(),viewport:new Viewport(),requestRender(){}};
const documents = new DocumentService({editor,services:{catalog,routeService},getViewportSize:()=>({width:1280,height:800}),notify(){}});
documents.loadDemo();
const drawing = structuredClone(store.state);
assert.equal(Object.keys(drawing.wires).length,7);
documents.newDocument();
assert.equal(Object.keys(store.state.components).length,0);
assert(store.undo());
assert.deepEqual(store.state,drawing,'Nuevo no pierde el plano ni sus conexiones');
assert(store.redo());
assert.equal(Object.keys(store.state.components).length,0);
documents.loadState(drawing);
assert.deepEqual(store.state,drawing);
assert(store.undo());
assert.equal(Object.keys(store.state.components).length,0,'Abrir es una operación deshacible');
console.log('OK — nuevo, abrir y ejemplo conservan el historial del documento.');

// Regresión gráfica: la bobina del contactor no debe ocupar el conductor L3.
const { symbolShapesFor } = await import('../src/data/symbolLibrary.js');
const definition = catalog.get('siemens.3rt2016.24vdc');
const rightPole = Math.max(...definition.terminals.filter(t => t.side === 'top').map(t => t.x));
const coil = symbolShapesFor(definition).find(s => s.t === 'rect');
assert(coil.x > rightPole);
assert(coil.x + coil.w < definition.width);
console.log('OK — bobina separada de los polos de potencia.');
