import assert from 'node:assert/strict';
import { createDefaultCatalog } from '../src/data/defaultCatalog.js';
import { createCommands } from '../src/core/commands.js';
import { createEmptyState, migrateState } from '../src/core/documentState.js';
import { DocumentStore } from '../src/core/documentStore.js';
import { hitTestComponent } from '../src/interaction/hitTesting.js';
import { alignComponents } from '../src/core/align.js';
import { componentLabelLayout } from '../src/core/textLayout.js';
import { wireLabelText } from '../src/core/wireLabel.js';
import { serializeDocument, parseDocument } from '../src/io/elcadFormat.js';
import { exportSvg } from '../src/io/svgExporter.js';
import { RouteService } from '../src/core/routeService.js';
import { WireRouter } from '../src/core/wireRouter.js';
import { HopCalculator } from '../src/core/wireGeometry.js';
const catalog = createDefaultCatalog(), commands = createCommands(catalog);
let state = createEmptyState();
const cabinet = commands.makeComponent(state, 'layout.enclosure.600x800', 300, 400);
state = commands.addComponent(state, cabinet);
const electrode = commands.makeComponent(state, 'field.flame.ionization', 100, 100);
state = commands.addComponent(state, electrode);
const store = new DocumentStore(state);
store.apply(s => commands.updateComponent(s, cabinet.id, { locked:true }));
const locked = store.state;
assert.equal(hitTestComponent({x:500,y:700},locked,catalog),null);
assert.equal(hitTestComponent({x:100,y:100},locked,catalog),electrode.id);
assert.ok(commands.removeEntities(locked,[cabinet.id]).components[cabinet.id]);
assert.deepEqual(commands.moveComponents(locked,[cabinet.id],50,50).components[cabinet.id],locked.components[cabinet.id]);
assert.deepEqual(commands.rotateComponents(locked,[cabinet.id]).components[cabinet.id],locked.components[cabinet.id]);
assert.deepEqual(alignComponents(locked,catalog,[cabinet.id,electrode.id],'left'),locked);
assert.equal(commands.duplicateComponents(locked,[cabinet.id],10,10).ids.length,0);
store.undo(); assert.equal(store.state.components[cabinet.id].locked,undefined);
store.redo(); assert.equal(store.state.components[cabinet.id].locked,true);
state=commands.updateComponent(locked,electrode.id,{label:'Sonda temperatura larga',labelOrientation:'vertical',terminalOrientation:'vertical',bodyTextOrientation:'horizontal'});
const routeService=new RouteService(catalog,new WireRouter());
const svg=exportSvg({state,catalog,routeService,hopCalculator:new HopCalculator({radius:3})});
assert.match(svg,/rotate\(-90\)/);
assert.match(svg,/Sonda temperatura larga/);
const layout=componentLabelLayout(state.components[electrode.id],catalog.resolve(electrode));
assert.ok(layout.bounds.top<0,'etiqueta vertical larga expande límites de exportación');
assert.deepEqual(await parseDocument(await serializeDocument(state)),state);
assert.equal(wireLabelText({gauge:'1.5',label:'C1'},{wireNumber:true,wireGauge:false}),'C1');
assert.equal(wireLabelText({gauge:'1.5'},{wireGauge:false}),'');
const copy=commands.duplicateComponents(state,[electrode.id],10,10);
assert.equal(copy.state.components[copy.ids[0]].labelOrientation,'vertical');
const bad=migrateState({...state,components:{[electrode.id]:{...electrode,locked:'false',labelOrientation:'bogus'}}});
assert.equal(bad.components[electrode.id].locked,undefined);
assert.equal(bad.components[electrode.id].labelOrientation,undefined);
assert.equal(catalog.resolve(electrode).terminals[0].id,'ION');
console.log('OK — bloqueo, historial, texto vertical/SVG, límites, rótulos, persistencia, validación y sonda.');
